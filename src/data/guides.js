export const getGuideBySlug = (slug) => guides.find((guide) => guide.slug === slug);

export function normalizeSection(section) {
  if (Array.isArray(section)) {
    return { heading: section[0], paragraphs: section[1] };
  }
  return section;
}

export function guidePlainText(guide) {
  const chunks = [...(guide.intro || [])];
  for (const raw of guide.sections || []) {
    const item = normalizeSection(raw);
    chunks.push(item.heading);
    (item.paragraphs || []).forEach((paragraph) => chunks.push(paragraph));
    (item.list || []).forEach((itemText) => chunks.push(itemText));
    (item.h3s || []).forEach((block) => {
      chunks.push(block.heading);
      (block.paragraphs || []).forEach((paragraph) => chunks.push(paragraph));
      (block.list || []).forEach((itemText) => chunks.push(itemText));
    });
    if (item.callout) chunks.push(item.callout.title, item.callout.text);
  }
  if (guide.checklist) {
    chunks.push(guide.checklist.title);
    guide.checklist.items.forEach((item) => chunks.push(item));
  }
  (guide.faq || []).forEach(([question, answer]) => chunks.push(question, answer));
  return chunks.join(" ").replace(/\[\[(.+?)\|(.+?)\]\]/g, "$2");
}

export function guideWordCount(guide) {
  return guidePlainText(guide).trim().split(/\s+/).filter(Boolean).length;
}

export function guideReadingMinutes(guide) {
  return Math.max(1, Math.round(guideWordCount(guide) / 200));
}
