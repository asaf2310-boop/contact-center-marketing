export function buildAgreementPlainText(clientName) {
  const sections = buildAgreementSections();
  const header = `הסכם שירותי פיתוח ותחזוקה\nלקוח/ה: ${clientName || "[שם הלקוח]"}\nנותן שירות: ${AGREEMENT_PROVIDER.name}\n`;
  const body = sections.map((s) => `${s.title}\n${s.body}`).join("\n\n");
  return `${header}\n${body}`;
}
